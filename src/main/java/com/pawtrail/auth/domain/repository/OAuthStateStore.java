package com.pawtrail.auth.domain.repository;

import java.util.Optional;

/**
 * 소셜 로그인 한 번을 이어 주는 값을 보관하는 약속입니다.
 *
 * 이 인터페이스에는 Redis 라는 단어가 나오지 않습니다.
 * 무엇을 할 수 있는지만 적고 어떻게 하는지는 infrastructure 가 정합니다.
 * 다른 저장소 셋과 같은 규칙입니다.
 *
 * 두 값을 다룹니다
 *
 *   state   되돌아온 요청이 우리가 시작한 것인지 확인하는 값입니다
 *   nonce   받은 신원 토큰이 그 요청에 대한 응답이 맞는지 확인하는 값입니다
 *
 * 항목은 하나만 만듭니다. state 를 키로, nonce 를 값으로 둡니다.
 * 둘을 따로 저장하면 어느 nonce 가 어느 state 의 짝인지 이어 줄 것이 없어지고,
 * 키가 둘이 되어 만료가 어긋날 여지도 생깁니다.
 *
 * state 가 왜 필요한가
 *
 * 인가 흐름은 브라우저가 제공자에 갔다가 우리 콜백으로 돌아오는 형태입니다.
 * 남이 자기 계정으로 인가를 받아 만든 콜백 주소를 피해자에게 열게 하면,
 * 피해자의 브라우저가 공격자 계정으로 로그인된 상태가 됩니다.
 * 시작할 때 만든 값이 돌아온 값과 같은지 보면 그 흐름을 걸러 냅니다.
 *
 * nonce 가 왜 필요한가
 *
 * 신원 토큰은 서명이 맞으면 유효해 보이므로, 앞서 오간 토큰을 손에 넣어
 * 다시 밀어 넣는 것을 서명만으로는 구분할 수 없습니다.
 * 우리가 만든 값이 그 토큰 안에 들어 있는지 보면 이번 요청에 대한 응답인지 갈립니다.
 *
 * 테이블을 만들지 않는 이유는 만료가 이 값의 본질이기 때문입니다.
 * 로그인 한 번을 잇는 동안만 살아 있으면 되고, 남길 가치도 없는 이력이 쌓입니다.
 * 이메일 인증 코드와 같은 성격입니다.
 */
public interface OAuthStateStore {

    /**
     * state 와 그 짝인 nonce 를 저장합니다.
     *
     * 수명은 짧게 둡니다.
     * 제공자 화면에서 계정을 고르고 동의하는 시간이면 충분하고,
     * 길게 두면 잃어버린 값이 그만큼 오래 쓸 수 있는 상태로 남습니다.
     */
    void save(String state, String nonce);

    /**
     * state 에 해당하는 nonce 를 꺼내면서 항목을 지웁니다. 없으면 비어 있습니다.
     *
     * 확인과 삭제를 나누지 않는 것은 의도입니다.
     * 나누면 두 요청이 같은 state 로 동시에 들어왔을 때 둘 다 통과합니다.
     * 꺼내면서 지우는 명령은 저장소 안에서 한 번에 처리되므로 하나만 값을 받습니다.
     *
     * 그 결과로 같은 콜백 주소를 두 번 열면 두 번째는 거부됩니다.
     * 인가 코드 자체도 1회용이지만 그쪽은 제공자가 판단하는 것이고,
     * 이것은 우리 쪽에서 같은 사실을 먼저 확인하는 장치입니다.
     */
    Optional<String> consume(String state);
}
