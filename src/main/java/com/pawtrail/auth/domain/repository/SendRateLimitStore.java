package com.pawtrail.auth.domain.repository;

/**
 * 메일 발송 횟수를 세는 약속입니다.
 *
 * 가입 인증과 비밀번호 재설정이 같은 것을 씁니다.
 * 두 기능이 코드 저장소는 나눠 쓰지만, 발송을 막는 규칙은 완전히 같습니다.
 *
 * 왜 필요한가
 *
 * 두 발송 경로 모두 인증이 필요 없어 누구나 계속 부를 수 있습니다.
 * 막지 않으면 두 가지가 일어납니다.
 *   남의 주소로 메일이 쏟아짐
 *   하루 발송 한도가 소진되어 정상 사용자도 메일을 받지 못함
 *
 * 발송 한도가 하루 500통뿐이라 뒤엣것이 특히 현실적입니다.
 *
 * 두 가지를 함께 봅니다
 *
 *   쿨다운      같은 주소로 짧은 시간에 연달아 보내지 못하게 함
 *   시간당 상한  같은 주소로 한 시간에 보낼 수 있는 총량
 *
 * 하나만으로는 부족합니다.
 * 쿨다운만 있으면 주소를 바꿔 가며 부르는 것을 못 막고,
 * 상한만 있으면 그 한도까지는 순식간에 몰아서 보낼 수 있습니다.
 *
 * 왜 "물어보기" 가 아니라 "자리 잡기" 인가
 *
 * 처음에는 보낼 수 있는지 묻는 메서드와 보냈다고 기록하는 메서드를 나눠 두었습니다.
 * 그런데 그 둘 사이에 메일 발송이 들어가 몇 초가 벌어지고,
 * 그동안 저장소에는 아무 흔적도 남지 않습니다.
 * 같은 주소로 요청을 동시에 보내면 전부 확인을 통과해 제한이 그대로 뚫립니다.
 *
 * 그래서 묻는 대신 자리를 잡습니다.
 * 자리를 잡은 요청만 발송으로 넘어가고 나머지는 그 자리에서 돌아갑니다.
 *
 * 막지 못하는 것
 *
 * 주소를 계속 바꾸는 공격은 이것으로 막히지 않습니다.
 * 그러려면 요청한 곳을 기준으로 세야 하는데, 게이트웨이가 원래 주소를 전달하지 않아
 * 지금은 그 값을 알 수 없습니다. 그것을 정하는 시점에 함께 볼 일입니다.
 */
public interface SendRateLimitStore {

    /**
     * 발송할 자리를 잡습니다.
     *
     * 자리를 잡았으면 참이고, 그때만 메일을 보냅니다.
     * 쿨다운 중이거나 시간당 상한을 넘겼으면 거짓입니다.
     * 둘 중 어느 쪽에 걸렸는지는 구분하지 않습니다.
     * 부르는 쪽이 하는 일이 어느 경우든 "보내지 않는다" 하나뿐이기 때문입니다.
     *
     * 이 메서드는 저장소의 값을 바꿉니다.
     * 참을 받았으면 반드시 recordSent 나 release 중 하나로 끝을 맺어야 합니다.
     */
    boolean tryAcquire(String email);

    /**
     * 보냈다는 것을 기록합니다.
     *
     * 시간당 카운터를 하나 올립니다. 쿨다운은 자리를 잡을 때 이미 시작되었습니다.
     *
     * 발송에 성공한 뒤에만 부릅니다.
     * 시도만 하고 실패한 것까지 세면 메일 서버가 잠시 죽었을 때
     * 정상 사용자가 한도를 다 쓰고 막힙니다.
     */
    void recordSent(String email);

    /**
     * 잡아 둔 자리를 돌려줍니다.
     *
     * 발송이 실패했을 때 부릅니다.
     * 그러지 않으면 메일이 오지도 않았는데 다음 요청이 쿨다운에 막힙니다.
     */
    void release(String email);
}
