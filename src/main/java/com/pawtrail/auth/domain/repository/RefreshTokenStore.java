package com.pawtrail.auth.domain.repository;

import java.time.Duration;
import java.util.Optional;
import java.util.UUID;

/**
 * 리프레시 토큰을 보관하는 약속입니다.
 *
 * 이 인터페이스에는 Redis 라는 단어가 나오지 않습니다.
 * 무엇을 할 수 있는지만 적고 어떻게 하는지는 infrastructure 가 정합니다.
 * JPA 리포지터리를 나눈 것과 같은 규칙입니다.
 *
 * 왜 데이터베이스가 아니라 별도 저장소인가
 *
 * 로그아웃할 때 토큰을 즉시 못 쓰게 만들어야 하는데,
 * JWT 는 발급된 뒤에는 만료 시각이 될 때까지 유효합니다.
 * 그래서 발급한 토큰을 따로 적어 두고, 갱신 요청이 올 때
 * "그 토큰이 아직 목록에 있는가" 를 확인합니다.
 * 로그아웃은 그 기록을 지우는 것으로 끝납니다.
 *
 * refresh_token_log 테이블은 이것과 별개입니다.
 * 그쪽은 "언제 어디서 발급됐는가" 를 남기는 이력이고, 여기는 유효성 판단용입니다.
 *
 * 두 가지를 보관합니다
 *
 *   살아 있는 토큰   갱신에 쓸 수 있는 토큰입니다. 수명은 리프레시 토큰과 같습니다.
 *   유예 항목        방금 교체된 토큰입니다. 짧은 시간 동안만 남습니다.
 *
 * 유예 항목이 왜 필요한가
 *
 * 갱신할 때 리프레시 토큰도 함께 새로 발급합니다.
 * 토큰이 복제됐을 때 수명을 짧게 끊고, 이미 쓴 토큰이 다시 들어오는 것을 탐지하기 위해서입니다.
 *
 * 그런데 탭 두 개가 같은 쿠키로 동시에 갱신을 부르면 뒤엣것은 이미 교체된 토큰을 들고 옵니다.
 * 응답을 못 받고 몇 초 뒤 재시도하는 경우도 같은 모양입니다.
 * 이것을 곧바로 복제로 처리하면 정상 사용자가 모든 기기에서 로그아웃되고,
 * 증상이 "가끔 로그아웃된다" 로만 나타나 원인을 짚기 어렵습니다.
 *
 * 그래서 교체된 토큰을 짧은 시간 동안 남겨 두고, 그 안에 들어온 재사용은
 * 경합으로 보아 앞서 발급한 토큰을 그대로 다시 내줍니다.
 * 시간이 지난 뒤의 재사용만 복제로 봅니다.
 *
 * 유예는 직전 토큰에만 적용됩니다.
 * 교체할 때마다 그 한 세대에 대해서만 항목을 남기므로,
 * 두 세대 전 토큰이 들어오면 항목이 없어 그대로 복제로 판정됩니다.
 *
 * 교체는 한 덩어리여야 합니다
 *
 * 옛 토큰을 써 버리는 것, 새 토큰을 활성화하는 것, 유예 항목을 남기는 것이
 * 나뉘면 그 중간 상태가 다른 요청에 보입니다.
 * 특히 "유예 항목은 보이는데 새 토큰은 아직 활성화되지 않은" 구간이 위험합니다.
 * 그 사이에 들어온 요청은 쓸 수 없는 토큰을 받아 가고, 그것으로 다시 갱신하면
 * 저장소에 없으므로 복제로 판정되어 계정 전체가 폐기됩니다.
 *
 * 그 구간을 줄이는 방식으로 두 번 고쳐 봤지만 병렬 요청 검증에서 두 번 다 깨졌습니다.
 * 키가 셋이라 단일 키 명령으로는 닫을 수 없는 구간이며, 그래서 rotate 하나로 묶었습니다.
 */
public interface RefreshTokenStore {

    /**
     * 발급한 토큰을 기록합니다. 로그인이 이것을 부릅니다.
     *
     * @param tokenId JWT 의 jti 입니다.
     * @param accountId 그 토큰이 가리키는 계정입니다.
     * @param ttl 토큰의 남은 수명입니다. 이 시간이 지나면 기록이 저절로 사라집니다.
     */
    void save(String tokenId, UUID accountId, Duration ttl);

    /**
     * 옛 토큰을 새 토큰으로 교체합니다.
     *
     * 세 가지가 한 덩어리로 처리됩니다.
     *   옛 토큰을 써 버림
     *   새 토큰을 활성화함
     *   동시 요청에게 내줄 유예 항목을 남김
     *
     * 옛 토큰이 살아 있었으면 그 계정 식별자를 돌려줍니다. 교체가 끝난 상태입니다.
     *
     * 비어 있으면 옛 토큰이 이미 없었다는 뜻이고, 이때는 아무것도 바뀌지 않습니다.
     * 다른 요청이 방금 먼저 교체했거나, 교체된 지 오래됐거나, 로그아웃된 토큰입니다.
     * 어느 쪽인지는 findGrace 로 가릅니다.
     *
     * @param oldTokenId    써 버릴 토큰의 jti 입니다.
     * @param newTokenId    활성화할 토큰의 jti 입니다.
     * @param newTokenValue 유예 항목에 담을 새 리프레시 토큰 문자열입니다.
     * @param ttl           새 토큰의 남은 수명입니다.
     * @param graceTtl      유예 시간입니다. app.auth.rotation-grace 에서 옵니다.
     */
    Optional<UUID> rotate(String oldTokenId, String newTokenId, String newTokenValue,
                          Duration ttl, Duration graceTtl);

    /**
     * 교체된 토큰에 딸린 새 토큰을 찾습니다.
     *
     * 값이 있으면 유예 시간 안의 재사용이므로 경합입니다.
     * 교체가 한 덩어리로 처리되므로, 이 값이 보인다는 것은
     * 그 안에 담긴 토큰이 이미 활성화되어 있다는 뜻이기도 합니다.
     *
     * 비어 있으면 유예가 지났거나 애초에 우리가 발급한 적이 없는 토큰이며,
     * 그때는 복제로 봅니다.
     */
    Optional<String> findGrace(String tokenId);

    /**
     * 토큰을 회수합니다. 로그아웃이 이것을 부릅니다.
     *
     * 값을 돌려주면서 동시에 지웁니다.
     * 확인과 삭제를 나누면 그 사이에 다른 요청이 같은 토큰을 확인하고 지나갈 수 있습니다.
     *
     * 돌려받은 계정 식별자를 쓰지 않아도 됩니다.
     * 지우는 것이 목적이고 반환값은 그 토큰이 살아 있었는지를 알려 줄 뿐입니다.
     */
    Optional<UUID> claim(String tokenId);
}
