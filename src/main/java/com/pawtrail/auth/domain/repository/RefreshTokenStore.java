package com.pawtrail.auth.domain.repository;

import java.time.Duration;
import java.util.Optional;
import java.util.UUID;

/**
 * 리프레시 토큰을 보관하는 약속입니다.
 *
 * 이 인터페이스에는 Redis 라는 단어가 나오지 않습니다.
 * 무엇을 할 수 있는지만 적고 어떻게 하는지는 infrastructure 가 정합니다.
 * JPA 리포지터리를 나눈 것과 같은 규칙입니다.
 *
 * 왜 데이터베이스가 아니라 별도 저장소인가
 *
 * 로그아웃할 때 토큰을 즉시 못 쓰게 만들어야 하는데,
 * JWT 는 발급된 뒤에는 만료 시각이 될 때까지 유효합니다.
 * 그래서 발급한 토큰을 따로 적어 두고, 갱신 요청이 올 때
 * "그 토큰이 아직 목록에 있는가" 를 확인합니다.
 * 로그아웃은 그 기록을 지우는 것으로 끝납니다.
 *
 * refresh_token_log 테이블은 이것과 별개입니다.
 * 그쪽은 "언제 어디서 발급됐는가" 를 남기는 이력이고, 여기는 유효성 판단용입니다.
 *
 * 두 가지를 보관합니다
 *
 *   살아 있는 토큰   갱신에 쓸 수 있는 토큰입니다. 수명은 리프레시 토큰과 같습니다.
 *   유예 항목        방금 교체된 토큰입니다. 짧은 시간 동안만 남습니다.
 *
 * 유예 항목이 왜 필요한가
 *
 * 갱신할 때 리프레시 토큰도 함께 새로 발급합니다.
 * 토큰이 복제됐을 때 수명을 짧게 끊고, 이미 쓴 토큰이 다시 들어오는 것을 탐지하기 위해서입니다.
 *
 * 그런데 탭 두 개가 같은 쿠키로 동시에 갱신을 부르면 뒤엣것은 이미 교체된 토큰을 들고 옵니다.
 * 응답을 못 받고 몇 초 뒤 재시도하는 경우도 같은 모양입니다.
 * 이것을 곧바로 복제로 처리하면 정상 사용자가 모든 기기에서 로그아웃되고,
 * 증상이 "가끔 로그아웃된다" 로만 나타나 원인을 짚기 어렵습니다.
 *
 * 그래서 교체된 토큰을 짧은 시간 동안 남겨 두고, 그 안에 들어온 재사용은
 * 경합으로 보아 앞서 발급한 토큰을 그대로 다시 내줍니다.
 * 시간이 지난 뒤의 재사용만 복제로 봅니다.
 *
 * 유예는 직전 토큰에만 적용됩니다.
 * 교체할 때마다 그 한 세대에 대해서만 항목을 남기므로,
 * 두 세대 전 토큰이 들어오면 항목이 없어 그대로 복제로 판정됩니다.
 *
 * 순서가 중요합니다
 *
 * 유예 항목을 먼저 선점하고 그다음에 토큰을 씁니다. 반대로 하면 안 됩니다.
 * 토큰을 먼저 쓰면 그 순간부터 유예 항목이 놓일 때까지 아무 흔적도 없는 구간이 생기고,
 * 동시에 들어온 요청이 그 구간에 닿으면 아무 잘못 없이 복제로 판정됩니다.
 * 실제로 그 구간을 최대한 줄여 봤지만 병렬 요청에 계속 걸렸습니다.
 * 선점을 먼저 하면 그 구간 자체가 없어집니다.
 */
public interface RefreshTokenStore {

    /**
     * 발급한 토큰을 기록합니다.
     *
     * @param tokenId JWT 의 jti 입니다.
     * @param accountId 그 토큰이 가리키는 계정입니다.
     * @param ttl 토큰의 남은 수명입니다. 이 시간이 지나면 기록이 저절로 사라집니다.
     */
    void save(String tokenId, UUID accountId, Duration ttl);

    /**
     * 교체할 자리를 잡으면서 새 토큰을 함께 남깁니다.
     *
     * 자리를 잡았으면 참입니다. 그 요청만 교체로 넘어갑니다.
     * 거짓이면 다른 요청이 이미 같은 토큰을 교체하는 중이거나 교체했다는 뜻이며,
     * 그때는 findGrace 로 그쪽이 남긴 토큰을 받아 그대로 돌려주면 됩니다.
     *
     * 자리를 잡았다고 해서 그 토큰이 살아 있다는 뜻은 아닙니다.
     * 유예 시간이 지난 뒤의 재사용도 항목이 비어 있으므로 여기서 참을 받습니다.
     * 살아 있는지는 이어서 claim 으로 확인합니다.
     *
     * @param tokenId          교체하려는 토큰의 jti 입니다.
     * @param replacementToken 그 대신 발급한 리프레시 토큰입니다.
     * @param ttl              유예 시간입니다. app.auth.rotation-grace 에서 옵니다.
     */
    boolean saveGraceIfAbsent(String tokenId, String replacementToken, Duration ttl);

    /**
     * 교체된 토큰에 딸린 새 토큰을 찾습니다.
     *
     * 값이 있으면 유예 시간 안의 재사용이므로 경합입니다.
     */
    Optional<String> findGrace(String tokenId);

    /**
     * 잡아 둔 자리를 돌려줍니다.
     *
     * 자리는 잡았는데 그 토큰이 이미 죽어 있던 경우에 부릅니다.
     * 즉 복제로 판정된 자리입니다.
     *
     * 그대로 두면 뒤이은 재사용이 여기 담긴 토큰을 경합으로 받아 가는데,
     * 그 토큰은 저장소에 기록된 적이 없어 아무 데도 쓸 수 없습니다.
     * 쓸 수 없는 값을 성공으로 돌려주는 상태가 되어 원인을 짚기 어려워집니다.
     */
    void deleteGrace(String tokenId);

    /**
     * 토큰을 써 버립니다. 값을 돌려주면서 동시에 지웁니다.
     *
     * 갱신과 로그아웃이 모두 이것을 부릅니다.
     * 갱신은 "이 토큰을 지금부터 내가 쓴다" 는 뜻이고, 로그아웃은 회수한다는 뜻인데
     * 저장소에 해야 할 일은 둘 다 "읽으면서 지운다" 로 같습니다.
     *
     * 확인과 삭제를 나누지 않는 것은 의도입니다.
     * 나누면 그 사이에 다른 요청이 같은 토큰을 확인하고 지나갈 수 있어,
     * 같은 토큰으로 두 벌의 새 토큰이 발급되고 한 벌이 주인 없이 살아남습니다.
     *
     * 비어 있으면 만료됐거나, 로그아웃됐거나, 유예가 지난 뒤에 다시 들어온 토큰입니다.
     */
    Optional<UUID> claim(String tokenId);
}
