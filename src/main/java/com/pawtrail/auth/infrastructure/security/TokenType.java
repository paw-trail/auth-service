package com.pawtrail.auth.infrastructure.security;

/**
 * 토큰의 종류입니다.
 *
 * 액세스 토큰과 리프레시 토큰은 담는 내용이 완전히 같고 수명만 다릅니다.
 * 리프레시에 내용을 줄이지 않은 것은 갱신할 때 그 토큰만으로
 * 새 액세스 토큰을 만들 수 있어야 하기 때문입니다.
 *
 * 그래서 종류를 표시하지 않으면 서로를 대신 쓸 수 있게 됩니다.
 *
 *   리프레시 토큰을 액세스 쿠키에 넣으면
 *     게이트웨이가 서명과 만료만 보므로 그대로 통과합니다.
 *     그 경로는 갱신 요청을 한 번도 거치지 않아 로테이션도 재사용 탐지도 걸리지 않고,
 *     계정의 토큰 폐기 기준 시각도 확인되지 않습니다.
 *
 *   액세스 토큰을 갱신 요청에 보내면
 *     서명은 통과하는데 그 jti 가 저장소에 없어 복제로 판정됩니다.
 *     액세스 토큰은 모든 요청에 실려 나가 리프레시보다 노출이 크므로,
 *     그것을 주운 사람이 한 번 보내는 것만으로 계정이 통째로 잠깁니다.
 *
 * 이 값은 payload 에 들어갑니다.
 * JWT 헤더에도 typ 이라는 표준 항목이 있으나 그쪽은 "이것이 JWT 다" 를 뜻하는 별개의 값입니다.
 *
 * 게이트웨이는 이 열거형을 쓸 수 없어 같은 문자열을 자기 코드에 따로 둡니다.
 * 공통 모듈을 의존하지 않기 때문이며, permit-all 목록이나 토픽 이름과 같은 성격입니다.
 */
public enum TokenType {

    ACCESS("access"),
    REFRESH("refresh");

    private final String value;

    TokenType(String value) {
        this.value = value;
    }

    /**
     * 토큰에 실제로 담기는 문자열입니다.
     *
     * 열거형 이름을 그대로 쓰지 않는 것은 의도입니다.
     * name() 을 쓰면 상수 이름을 바꾸는 순간 이미 발급된 토큰이 전부 거부되는데,
     * 그 연결이 코드에 드러나지 않아 안전한 이름 변경처럼 보입니다.
     */
    public String value() {
        return value;
    }

    /**
     * 토큰에서 꺼낸 값이 이 종류인지 봅니다.
     *
     * @param raw 토큰에 담겨 있던 문자열입니다. null 이면 종류가 없는 옛 토큰입니다.
     */
    public boolean matches(String raw) {
        return this.value.equals(raw);
    }
}
