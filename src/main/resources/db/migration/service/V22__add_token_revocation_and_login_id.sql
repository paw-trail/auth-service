-- 토큰 일괄 폐기 기준 시각과 로그인 사슬 식별자를 추가합니다.
--
-- V20 과 V21 은 이미 develop 에 들어갔으므로 고치지 않고 새 번호로 만듭니다.

-- =============================================================================
-- account.tokens_valid_from
-- =============================================================================
-- 이 시각 이후에 발급된 토큰만 유효하다는 뜻입니다.
--
-- 비밀번호를 바꾸면 이 값을 그 시각으로 올립니다.
-- 그러면 이전에 발급된 리프레시 토큰은 갱신 요청 때 전부 거부됩니다.
-- 비밀번호를 바꾸는 이유가 보통 "누가 내 계정에 들어온 것 같다" 이므로,
-- 바꿔도 기존 세션이 살아 있으면 그 행위의 목적이 절반만 달성됩니다.
--
-- 왜 계정에 시각 하나를 두는 방식인가
--
-- 리프레시 토큰은 Redis 의 refresh:{jti} 에 있어 계정으로 찾을 수 없습니다.
-- 계정별 jti 목록을 따로 들고 있는 방법도 있으나, 목록 안의 항목은 토큰이 만료돼도
-- 사라지지 않아 쓰레기가 쌓이고 Redis 와 동기화할 곳이 두 군데가 됩니다.
-- 시각 하나만 올리면 지울 것이 없고 "모든 기기에서 로그아웃" 도 같은 방법으로 됩니다.
--
-- NULL 을 허용하지 않는 이유
--
-- 이 값을 읽는 자리는 갱신 요청이 들어올 때마다 도는 경로입니다.
-- NULL 을 허용하면 비교 앞에 NULL 검사가 하나 붙는데, 그것을 빠뜨려도
-- 테스트는 통과하고 대신 모든 갱신이 그냥 통과해 버립니다.
-- 기본값을 두어 분기 자체를 없앱니다.

-- 기존 행이 있을 수 있으므로 세 단계로 나눕니다.
-- NOT NULL 을 처음부터 걸면 값이 없는 기존 행 때문에 실패합니다.
ALTER TABLE account
    ADD COLUMN tokens_valid_from timestamp;

-- 계정이 만들어진 시각으로 채웁니다.
-- 그 계정에서 지금까지 발급된 토큰은 모두 이 시각 뒤에 나온 것이므로
-- 살아 있던 세션이 이 마이그레이션 때문에 끊기지 않습니다.
UPDATE account
   SET tokens_valid_from = created_at
 WHERE tokens_valid_from IS NULL;

ALTER TABLE account
    ALTER COLUMN tokens_valid_from SET NOT NULL;

COMMENT ON COLUMN account.tokens_valid_from IS '이 시각 이후 발급된 토큰만 유효합니다.';

-- =============================================================================
-- refresh_token_log.login_id
-- =============================================================================
-- 로그인 한 번을 묶는 값입니다.
--
-- 갱신할 때마다 리프레시 토큰을 새로 발급하고 이 테이블에 행을 하나씩 더 쌓습니다.
-- 그러면 한 번의 로그인이 여러 행으로 흩어지는데, 그 행들을 이어 줄 수단이 없으면
-- 기기가 둘 이상일 때 어느 행이 어느 로그인에서 시작됐는지 알 수 없습니다.
--
-- 로그인할 때 만들고 갱신할 때 그대로 물려줍니다.
--
--   행  login_id  issued_at  revoked_at
--   X   A         09:00      09:30      <- 폰으로 로그인
--   Y   A         09:30      10:00
--   Z   A         10:00      NULL       <- 폰의 현재 토큰
--   P   B         14:00      14:30      <- PC 로 로그인
--   Q   B         14:30      NULL       <- PC 의 현재 토큰
--
-- 이 값이 있어야 "언제 어디서 로그인했나" 를 답할 수 있습니다.
-- 마지막 행의 issued_at 은 로그인 시각이 아니라 마지막 갱신 시각이며,
-- 로그인 시각은 그 사슬의 첫 행에 있습니다.
--
-- 인증 판단에는 쓰이지 않습니다.
-- 로그인, 갱신, 재사용 탐지, 토큰 폐기 어디에서도 이 값을 보지 않습니다.
-- 쓰기만 하고 읽는 것은 사람이 이 표를 들여다볼 때뿐이라
-- 성격이 Zipkin 의 traceId 에 가깝습니다.
--
-- 이름을 session_id 로 두지 않은 것은 의도입니다.
-- 서버 세션을 도입했다는 뜻으로 읽히는데, 이 서비스는 여전히 토큰 기반이며
-- 이 컬럼은 로그를 묶는 값일 뿐입니다.

ALTER TABLE refresh_token_log
    ADD COLUMN login_id uuid;

-- 기존 행은 로테이션이 없던 시절에 만들어진 것이라 각자가 하나의 로그인입니다.
-- 자기 id 를 그대로 넣으면 길이 1 짜리 사슬이 됩니다.
UPDATE refresh_token_log
   SET login_id = id
 WHERE login_id IS NULL;

ALTER TABLE refresh_token_log
    ALTER COLUMN login_id SET NOT NULL;

COMMENT ON COLUMN refresh_token_log.login_id IS '로그인 한 번을 묶는 값. 갱신해도 물려받습니다.';

-- login_id 에 인덱스를 만들지 않습니다.
--
-- 이 테이블은 갱신할 때마다 쓰기가 일어나는 로그이고 인덱스는 그 쓰기를 느리게 합니다.
-- 반면 login_id 로 하는 조회는 특정 계정을 조사할 때만 하는 드문 작업이며,
-- 그때도 idx_refresh_token_log_account 로 그 계정의 행만 먼저 좁혀지므로
-- 남은 것을 훑는 비용이 크지 않습니다.
-- 조사 화면을 실제로 만들면서 느리다고 판단되면 그때 새 번호로 추가합니다.

-- =============================================================================
-- 테이블 주석 갱신
-- =============================================================================
-- 회수 경로가 셋이 되어 기존 주석이 담지 못합니다.
--   로그아웃      그 토큰 하나
--   갱신          교체된 옛 토큰
--   일괄 폐기      그 계정의 유효한 토큰 전부
COMMENT ON TABLE refresh_token_log IS '리프레시 토큰 발급·회수 이력. 토큰 본체는 Redis 에 있습니다.';
