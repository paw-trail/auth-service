-- 탈퇴 인증 코드를 대조하고, 맞았을 때만 지움
--
-- 확인과 삭제가 한 덩어리로 실행되므로 그 중간 상태를 다른 요청이 볼 수 없음
--
-- 왜 하나로 묶는가
--
-- 나눠서 하면 두 요청이 같은 코드로 동시에 들어왔을 때 둘 다 대조를 통과함
-- 탈퇴는 상태 전이가 멱등이라 계정은 망가지지 않으나,
-- account.withdrawn 이벤트가 두 건 발행되어 토픽에 흔적이 남음
--
-- 왜 GETDEL 로는 안 되는가
--
-- GETDEL 은 값을 보지 않고 지움
-- 그러면 코드를 한 글자 틀리는 순간 진짜 코드가 사라져,
-- 다섯 번까지 다시 시도할 수 있게 해 둔 장치가 통째로 의미를 잃음
-- 오타는 흔한 일이고 그때마다 메일을 다시 받아야 하는데 발송 제한이 1분을 막음
--
-- 반환값
--   맞았으면 1   코드를 지웠음. 부르는 쪽이 탈퇴를 진행함
--   틀렸으면 0   코드는 그대로 남음. 부르는 쪽이 시도 횟수를 셈
--   없으면  -1   만료됐거나 요청한 적이 없음
--
-- 틀림과 없음을 갈라 돌려주는 것은 시도 횟수를 셀지 정하기 위함임
-- 없는 코드에 횟수를 세면 아무 의미가 없고, 부르는 쪽이 응답은 같게 냄
--
-- KEYS[1]  withdraw:{email}   보관된 코드
-- ARGV[1]  사용자가 입력한 코드

local saved = redis.call('GET', KEYS[1])

if not saved then
    return -1
end

if saved ~= ARGV[1] then
    return 0
end

redis.call('DEL', KEYS[1])
return 1
